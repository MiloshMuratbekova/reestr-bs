"""Каталог алгоритмов выявления БС.

Здесь собраны только метаданные и ссылки на SQL-файлы. Сам SQL при первом
старте загружается в PostgreSQL (таблица bs_algorithms) и дальше берётся
оттуда — так администратор может править алгоритм через интерфейс.

Имена таблиц результата взяты из ТЗ: БС-1 → AFM_6_1_7, БС-7 → AFM_6_1_13,
БС-13 → AFM_6_1_19, БС-22 → AFM_6_1_28 (то есть AFM_6_1_<N+6>).
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List

SQL_DIR = Path(__file__).parent / "sql"


@dataclass(frozen=True)
class AlgorithmDefinition:
    code: str
    slug: str
    name: str
    description: str
    result_table: str
    source: str
    priority_score: int
    order_index: int
    #: Расшифровка для промпта Qwen (текст из ТЗ)
    ai_hint: str
    depends_on: List[str] = field(default_factory=list)

    @property
    def sql_path(self) -> Path:
        return SQL_DIR / f"{self.slug}.sql"

    def load_sql(self) -> str:
        return self.sql_path.read_text(encoding="utf-8")


