"""Каталог алгоритмов выявления БС.

Здесь собраны только метаданные и ссылки на SQL-файлы. Сам SQL при первом
старте загружается в PostgreSQL (таблица bs_algorithms) и дальше берётся
оттуда — так администратор может править алгоритм через интерфейс.

Состав каталога соответствует итоговой таблице AFM_6_1_99: в реестр входят
таблицы результатов AFM_6_1_7 … AFM_6_1_19, AFM_6_1_21 … AFM_6_1_30.
Имя таблицы результата — AFM_6_1_<N+6>, где N — номер алгоритма.

Исключение одно — БС-14 (AFM_6_1_20): его нет в объединении AFM_6_1_99,
а состав полей источника не подтверждён, поэтому алгоритм отключён.
Остальные двадцать три участвуют в расчёте.

Порядок расчёта задаётся order_index, а зависимости — depends_on: БС-11 и
БС-13 читают результаты БС-1 и БС-3, БС-17 — регистрационные алгоритмы
и БС-22, а БС-24 замыкает расчёт и читает результаты всех остальных.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List

SQL_DIR = Path(__file__).parent / "sql"


@dataclass(frozen=True)
class AlgorithmDefinition:
    code: str
    slug: str
    name: str
    description: str
    result_table: str
    source: str
    priority_score: int
    order_index: int
    #: Расшифровка для промпта Qwen
    ai_hint: str
    depends_on: List[str] = field(default_factory=list)
    #: Участвует ли алгоритм в расчёте реестра сразу после установки
    is_active: bool = True

    @property
    def sql_path(self) -> Path:
        return SQL_DIR / f"{self.slug}.sql"

    def load_sql(self) -> str:
        return self.sql_path.read_text(encoding="utf-8")


