"""Приведение в порядок данных бенефициаров на чтении.

Таблицы результатов алгоритмов ведёт организация, и система работает с ними
только на чтение — исправить источник она не может. Поэтому мусор
разбирается здесь, при сборке реестра.

Что разбирается
---------------
1. ИИН. В поле попадают заглушки: 000000000, «-», пустая строка, а также
   текст вместо номера. Настоящим ИИН считается ровно двенадцать цифр,
   не все нули. Остальное обнуляется.

2. Имя. У части алгоритмов в поле ФИО лежит целая строка вида
   «, публичная компания с ограниченной ответственностью "Яндекс нв",
   тип участия: основатель, статус заявки: заявка отправлена».
   Настоящее наименование стоит в кавычках, поэтому оно и достаётся.
   Кавычки бывают разные: «ёлочки», "прямые", „лапки“.

3. Нерезиденты. Если ИИН нет и в тексте есть признак иностранного лица,
   человек или компания считается нерезидентом: статус получает пометку,
   а вместо пустого ИИН подставляется ключ, начинающийся со слова
   «нерезидент».

Почему ключ не просто «нерезидент»
----------------------------------
Реестр сводится по паре «компания + ИИН бенефициара». Если всем
нерезидентам одной компании выдать один и тот же ключ, они склеятся
в одну строку и разные люди станут неразличимы. Поэтому к слову
добавляется имя: ключ по-прежнему начинается с «нерезидент», отбор
по нему работает, но люди не смешиваются.
"""

from __future__ import annotations

#: Настоящий ИИН: двенадцать цифр и не все нули
VALID_IIN = (
    "match({col}, '^[0-9]{{12}}$') AND {col} != '000000000000'"
)

#: Явные заглушки, которые встречаются вместо ИИН
IIN_STUBS = ("'-'", "'--'", "'0'", "'000000000'", "'000000000000'", "'нет'", "'отсутствует'")


def clean_iin(col: str) -> str:
    """ИИН или пустая строка, если в поле заглушка либо текст."""
    stubs = ", ".join(IIN_STUBS)
    return (
        f"if(match(trimBoth({col}), '^[0-9]{{12}}$')"
        f" AND trimBoth({col}) != '000000000000'"
        f" AND lowerUTF8(trimBoth({col})) NOT IN ({stubs}),"
        f" trimBoth({col}), '')"
    )


def quoted_name(col: str) -> str:
    """Наименование из кавычек, если оно там есть.

    В поле ФИО у некоторых источников лежит длинная строка, где само
    название организации взято в кавычки, а вокруг — организационная форма
    и служебные пометки. Берётся содержимое первых кавычек любого вида.
    """
    return f"""extract({col}, '[«"„]([^»"“]{{2,}})')"""


def first_part(col: str) -> str:
    """Часть строки до первой запятой, без обрамляющих пробелов."""
    return f"trimBoth(splitByChar(',', {col})[1])"


#: Признаки того, что лицо иностранное. Проверяются по тексту, когда ИИН нет.
NONRESIDENT_MARKS = (
    "нерезидент",
    "иностран",
    "foreign",
    "non-resident",
)


def is_nonresident(iin_col: str, text_col: str, status_col: str) -> str:
    """Признак нерезидента: нет настоящего ИИН и есть пометка в тексте.

    Пустой ИИН сам по себе тоже считается признаком: у иностранных лиц
    казахстанского номера нет в принципе, и именно поэтому поле пустое.
    """
    marks = " OR ".join(
        f"positionCaseInsensitive({text_col}, '{mark}') > 0" for mark in NONRESIDENT_MARKS
    )
    status_mark = f"positionCaseInsensitive({status_col}, 'нерезидент') > 0"
    return f"({iin_col} = '' AND (({marks}) OR {status_mark} OR {text_col} != ''))"


def beneficiary_key(iin_col: str, name_col: str) -> str:
    """Ключ бенефициара: ИИН, а при его отсутствии — «нерезидент» с именем."""
    return (
        f"if({iin_col} != '', {iin_col},"
        f" if({name_col} != '', concat('нерезидент: ', {name_col}), 'нерезидент'))"
    )


def nonresident_status(status_col: str) -> str:
    """Тот же тип БС, но с пометкой о нерезидентстве."""
    return (
        f"if(positionCaseInsensitive({status_col}, 'Регистрационный') > 0,"
        f" 'Регистрационный БС - нерезидент', 'Предполагаемый БС - нерезидент')"
    )


def name_from_dop(dop_col: str, code_col: str, first_part_codes: str) -> str:
    """Имя по одному лишь dop_info, без справочника физических лиц.

    Сначала наименование из кавычек, затем правило «до первой запятой» для
    алгоритмов, у которых dop_info начинается с ФИО, иначе строка целиком.

    Справочник тут не нужен: он ищется по ИИН, а это выражение применяется
    как раз там, где настоящего ИИН нет.
    """
    quoted = quoted_name(dop_col)
    return (
        f"if({quoted} != '', {quoted},"
        f" if({code_col} IN ({first_part_codes}), {first_part(dop_col)}, {dop_col}))"
    )


#: Признак юрлица из ТЗ: пятый знак справа восьмизначной части БИН
IS_UL = "left(right({col}, 8), 1) IN ('4', '5')"


def unresolved_ul_status(status_col: str) -> str:
    """Тот же тип БС, но с пометкой о неразвёрнутой цепочке владения.

    Ставится юрлицу, которое не удалось довести до физического лица даже
    за четыре уровня. Бенефициаром такое ЮЛ не является, но скрывать его
    хуже, чем показать: аналитику видно, что зацепка есть и где она обрывается.
    """
    return (
        f"if(positionCaseInsensitive({status_col}, 'Регистрационный') > 0,"
        f" 'Регистрационный БС - цепочка не раскрыта',"
        f" 'Предполагаемый БС - цепочка не раскрыта')"
    )


#: Организационные формы. В поле ФИО должно остаться только имя, а форма —
#: это не имя. Список отсортирован от длинного к короткому: иначе «ОАО»
#: срежется раньше, чем «ОАО» внутри более длинного оборота.
LEGAL_FORMS = (
    "публичная компания с ограниченной ответственностью",
    "товарищество с ограниченной ответственностью",
    "общество с ограниченной ответственностью",
    "акционерное общество",
    "частное учреждение",
    "производственный кооператив",
    "индивидуальный предприниматель",
    "государственное предприятие",
    "оао", "зао", "пао", "тоо", "ооо", "ао", "ип", "чп", "кх",
)

#: Служебные ярлыки источника: всё, что после них, к имени не относится
SERVICE_MARKS = (
    "тип участия",
    "статус заявки",
    "доля участия",
    "доля",
    "гражданство",
    "резидентство",
    "вид участия",
    "идентификатор",
    "данные введены",
    "номер документа",
    "номер серии",
    "страна",
    "инфо",
    "статус",
)


def strip_legal_form(col: str) -> str:
    """Убирает организационную форму из начала наименования."""
    expr = col
    for form in LEGAL_FORMS:
        # Форма срезается только в начале строки и только целым словом,
        # иначе «АО» выкусит две буквы из середины настоящего названия
        expr = (
            f"trimBoth(replaceRegexpOne({expr},"
            f" '^(?i)\s*{form}\s+', ''))"
        )
    return expr


def cut_at_service_mark(col: str) -> str:
    """Обрезает строку на первом служебном ярлыке источника."""
    marks = "|".join(SERVICE_MARKS)
    return (
        f"trimBoth(replaceRegexpOne({col},"
        f" '(?i)[,;]?\s*({marks})\s*[:=].*$', ''))"
    )


def display_name(dop_col: str) -> str:
    """Только имя: ФИО человека либо наименование организации.

    Порядок: наименование из кавычек, иначе строка обрезается на служебном
    ярлыке и по первой запятой, затем снимается организационная форма и
    остатки знаков препинания.

    Правило «до первой запятой» применяется ко ВСЕМ алгоритмам, а не к трём,
    как раньше. Иначе одно и то же лицо, записанное разными алгоритмами
    по-разному, давало бы разные имена — а имя служит ключом сведения там,
    где ИИН отсутствует.
    """
    quoted = quoted_name(dop_col)
    trimmed = first_part(cut_at_service_mark(dop_col))
    return (
        f"trimBoth(trimBoth(if({quoted} != '', {quoted},"
        f" {strip_legal_form(trimmed)}), '\"«»„“'), ' .,;:-')"
    )


def display_iin(iin_col: str, nonresident_col: str) -> str:
    """Значение поля ИИН для показа: ИИН, слово «нерезидент» либо пусто.

    Служебный ключ сведения сюда не попадает: в поле ИИН пользователь ждёт
    номер, а не строку вида «нерезидент: Иванов Иван». Ключ живёт отдельным
    полем benefeciary_key и нужен только для ссылок и группировки.
    """
    return (
        f"if({iin_col} != '', {iin_col},"
        f" if({nonresident_col}, 'нерезидент', ''))"
    )


def display_iin_with_id(iin_col: str, nonresident_col: str, dop_col: str) -> str:
    """То же поле ИИН, но с иностранным идентификатором вместо слова.

    Порядок: настоящий ИИН, затем идентификатор из сведений, затем слово
    «нерезидент», затем пусто. Идентификатор точнее слова: по нему лицо
    можно опознать, а «нерезидент» одинаково у всех.
    """
    identifier = identifier_from_dop(dop_col)
    return (
        f"if({iin_col} != '', {iin_col},"
        f" if({identifier} != '', {identifier},"
        f" if({nonresident_col}, 'нерезидент', '')))"
    )


def clean_bin(col: str) -> str:
    """БИН компании: те же двенадцать цифр, иначе пусто."""
    return clean_iin(col)


#: Ярлык, под которым алгоритмы кладут иностранный идентификатор в dop_info.
#: Появился в обновлённых скриптах: если ИИН не 12 цифр, номер переносится
#: в строку сведений, чтобы не портить ключевое поле.
IDENTIFIER_MARK = "идентификатор"


def identifier_from_dop(dop_col: str) -> str:
    """Иностранный идентификатор из строки сведений, иначе пусто.

    Алгоритмы записывают его как «…, идентификатор: X, …». Читается всё
    до следующей запятой либо до конца строки.
    """
    return (
        f"trimBoth(extract({dop_col},"
        f" '(?i){IDENTIFIER_MARK}\s*[:=]\s*([^,;]+)'))"
    )


#: Как источник помечает организацию без казахстанского БИН
FOREIGN_COMPANY = "Иностранная компания"


def company_key(bin_col: str, name_col: str) -> str:
    """Служебный ключ компании: БИН, а при его отсутствии — имя иностранной.

    В сводной таблице у иностранных организаций вместо БИН стоит текст
    «Иностранная компания», одинаковый для всех. Оставь его ключом — и все
    они сольются в одну строку с общим набором бенефициаров. Поэтому к слову
    добавляется наименование: ключ по-прежнему начинается одинаково, отбор
    по нему работает, а компании не смешиваются.
    """
    return (
        f"if({bin_col} != '', {bin_col},"
        f" if({name_col} != '',"
        f" concat('{FOREIGN_COMPANY}: ', {name_col}), '{FOREIGN_COMPANY}'))"
    )


def display_company_bin(bin_col: str) -> str:
    """Поле БИН для показа: номер либо слово «Иностранная компания».

    Служебный ключ сюда не попадает: в поле БИН пользователь ждёт номер,
    а не строку с наименованием внутри.
    """
    return f"if({bin_col} != '', {bin_col}, '{FOREIGN_COMPANY}')"
